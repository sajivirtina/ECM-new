<?php
/**
 * Explanatory tooltips on the Cart / Checkout totals tables — next to
 * "Subtotal" / "Total" (the one-time, PRORATED first charge for the
 * partial period until the next billing date) and next to
 * "Recurring totals" / "Recurring total" (the full plan price billed every
 * month from then on).
 *
 * Why this exists: our WC Subscriptions plans renew on the 1st of the
 * month, but a provider can sign up any day — so the very first charge
 * (shown as "Subtotal"/"Total" at the top of the cart) is prorated for
 * just the days left until that renewal date, and looks smaller than the
 * "Recurring total" below it. Without an explanation, that reads as a
 * pricing mistake (e.g. "$12 now" vs "$38 / month" — see the Cart
 * screenshot this was built from). This adds a small (i) icon with a
 * one-line explanation next to each label.
 *
 * Implemented as a JS enhancement that matches rows by their LABEL TEXT
 * ("Subtotal", "Total", "Recurring totals", "Recurring total"), not a
 * cart-totals.php template override — the "Recurring totals" section
 * itself is generated by WooCommerce Subscriptions, not core WooCommerce
 * or this theme, and we don't have that plugin's exact template markup on
 * hand here. Matching on text is resilient to whatever markup it renders,
 * and re-runs after WooCommerce's own AJAX totals refresh (coupon apply,
 * qty update, shipping change) via the updated_cart_totals /
 * updated_checkout events it already fires.
 *
 * @package ElderCareMatters
 */

defined( 'ABSPATH' ) || exit;

add_action( 'wp_enqueue_scripts', function () {
	if ( ! function_exists( 'is_cart' ) || ! function_exists( 'is_checkout' ) ) {
		return; // WooCommerce not active.
	}
	if ( ! is_cart() && ! is_checkout() ) {
		return;
	}

	$one_time_tip  = __( "This is a one-time, prorated charge — it only covers the days left until your next billing date shown below. It won't repeat.", 'eldercare-matters' );
	$recurring_tip = __( "From your next billing date onward, you'll be charged this full amount every month.", 'eldercare-matters' );

	$css = '
		.ecm-tip { display:inline-flex; align-items:center; justify-content:center; width:16px; height:16px; margin-left:6px; border-radius:50%; background:#e4e4e4; color:#555; font-size:11px; font-weight:700; font-style:normal; line-height:1; cursor:help; position:relative; vertical-align:middle; }
		.ecm-tip:hover, .ecm-tip:focus { background:#cfd8d2; outline:none; }
		.ecm-tip::after {
			content: attr(data-tip);
			position:absolute; bottom:calc(100% + 8px); left:50%; transform:translateX(-50%);
			width:230px; max-width:60vw; padding:8px 10px; border-radius:6px;
			background:#2c2c2c; color:#fff; font-size:12px; font-weight:400; line-height:1.4;
			text-align:left; white-space:normal; opacity:0; pointer-events:none;
			transition:opacity .15s ease; z-index:20;
		}
		.ecm-tip::before {
			content:""; position:absolute; bottom:calc(100% + 3px); left:50%; transform:translateX(-50%);
			border:5px solid transparent; border-top-color:#2c2c2c; opacity:0; pointer-events:none;
			transition:opacity .15s ease;
		}
		.ecm-tip:hover::after, .ecm-tip:focus::after,
		.ecm-tip:hover::before, .ecm-tip:focus::before { opacity:1; }
	';

	wp_register_style( 'ecm-cart-tooltips', false );
	wp_enqueue_style( 'ecm-cart-tooltips' );
	wp_add_inline_style( 'ecm-cart-tooltips', $css );

	$js = '
	(function () {
		var ONE_TIME_TIP  = ' . wp_json_encode( $one_time_tip ) . ';
		var RECURRING_TIP = ' . wp_json_encode( $recurring_tip ) . ';

		function norm( text ) {
			return ( text || "" ).replace( /\s+/g, " " ).trim().toLowerCase();
		}

		function addTip( labelEl, text ) {
			if ( ! labelEl || labelEl.querySelector( ".ecm-tip" ) ) { return; }
			var tip = document.createElement( "span" );
			tip.className = "ecm-tip";
			tip.setAttribute( "data-tip", text );
			tip.setAttribute( "tabindex", "0" );
			tip.setAttribute( "role", "img" );
			tip.setAttribute( "aria-label", text );
			tip.textContent = "i";
			labelEl.appendChild( tip );
		}

		function run() {
			var containers = document.querySelectorAll( ".cart_totals, .woocommerce-checkout-review-order-table, .cart-collaterals, .order_details" );
			if ( ! containers.length ) { return; }

			var pastRecurringHeader = false;

			containers.forEach( function ( container ) {
				var rows = container.querySelectorAll( "tr, .woocommerce-order-overview__total" );
				rows.forEach( function ( row ) {
					var labelEl = row.querySelector( "th" ) || row.querySelector( "td:first-child" ) || row;
					var label   = norm( labelEl.textContent );

					if ( label === "recurring totals" ) {
						pastRecurringHeader = true;
						return;
					}
					if ( label === "subtotal" || label === "total" ) {
						addTip( labelEl, pastRecurringHeader ? RECURRING_TIP : ONE_TIME_TIP );
					} else if ( label.indexOf( "recurring total" ) === 0 ) {
						addTip( labelEl, RECURRING_TIP );
					}
				} );
			} );
		}

		document.addEventListener( "DOMContentLoaded", run );
		// Cart/checkout totals re-render via AJAX (coupon apply, shipping
		// change, qty update) — WooCommerce itself fires these events after
		// that refresh, so re-run there rather than only once on load.
		if ( window.jQuery ) {
			jQuery( document.body ).on( "updated_cart_totals updated_checkout", run );
		}
	})();
	';

	wp_register_script( 'ecm-cart-tooltips', '', [ 'jquery' ], null, true );
	wp_enqueue_script( 'ecm-cart-tooltips' );
	wp_add_inline_script( 'ecm-cart-tooltips', $js );
}, 30 );
